-- Uploaded documents (S3) and their asynchronous ingestion, plus keyword search.
--
-- A document's chunks are only ever replaced as a whole, in one transaction, by a
-- successful ingestion; retrieval reads chunks, so it sees a complete version of a
-- document or none. `status` describes the latest upload or processing run: a failed
-- re-upload keeps serving the previous complete version until a new one succeeds.
--
-- Rows written by 20261031000000_rag stay valid: they become `ready` documents with no
-- storage object.

-- Character trigrams for keyword search. Full-text search with the `simple` parser keeps
-- a Thai phrase as one token (Thai has no spaces between words), so it cannot match a
-- Thai word inside a sentence; trigrams can. Needs a database whose LC_CTYPE classifies
-- Thai letters as alphanumeric (en_US.UTF-8 does).
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- A pending upload has no content yet; a ready document always has a hash.
ALTER TABLE rag.documents ALTER COLUMN content_hash DROP NOT NULL;

ALTER TABLE rag.documents
    -- 'directory' = indexed from RAG_DOCS_DIR by the runtime; 's3' = uploaded.
    ADD COLUMN storage_provider      TEXT        CHECK (storage_provider IN ('directory', 's3')),
    ADD COLUMN storage_bucket        TEXT        CHECK (char_length(storage_bucket) BETWEEN 3 AND 63),
    -- Generated by the runtime, never taken from the client.
    ADD COLUMN object_key            TEXT        CHECK (char_length(object_key) BETWEEN 1 AND 1024),
    -- S3 version id of the ingested object, when the bucket is versioned.
    ADD COLUMN object_version        TEXT        CHECK (char_length(object_version) <= 1024),
    -- Detected from the content by the worker, not the client's Content-Type.
    ADD COLUMN mime_type             TEXT        CHECK (char_length(mime_type) <= 255),
    ADD COLUMN size_bytes            BIGINT      CHECK (size_bytes >= 0),
    ADD COLUMN status                TEXT        NOT NULL DEFAULT 'ready'
        CHECK (status IN ('pending_upload', 'queued', 'processing', 'ready', 'failed')),
    -- Why the latest run failed; safe to show to the uploader (no stack traces).
    ADD COLUMN error                 TEXT        CHECK (char_length(error) <= 2000),
    ADD COLUMN upload_requested_at   TIMESTAMPTZ,
    ADD COLUMN processing_started_at TIMESTAMPTZ,
    ADD COLUMN processed_at          TIMESTAMPTZ,
    ADD CONSTRAINT documents_s3_location
        CHECK (storage_provider IS DISTINCT FROM 's3'
               OR (storage_bucket IS NOT NULL AND object_key IS NOT NULL)),
    ADD CONSTRAINT documents_ready_has_hash
        CHECK (status <> 'ready' OR content_hash IS NOT NULL);

-- S3 events name the object; this finds its document.
CREATE UNIQUE INDEX documents_object ON rag.documents (storage_bucket, object_key)
    WHERE object_key IS NOT NULL;

-- Heading path inside the document ("Music > Uploads"), shown with the excerpt.
ALTER TABLE rag.chunks ADD COLUMN heading TEXT NOT NULL DEFAULT '' CHECK (char_length(heading) <= 2000);

CREATE INDEX chunks_content_trgm ON rag.chunks USING gin (content gin_trgm_ops);
-- Retrieval filters by embedding model, so vectors of different models are never compared.
CREATE INDEX chunks_document_model ON rag.chunks (document_id, embedding_model);

-- One row per (object, pipeline configuration): the idempotency key for ingestion. A
-- duplicate S3 event finds the existing job; a new upload (new object key), a new object
-- version, or a change of parser, chunking or embedding model creates a new one.
CREATE TABLE rag.ingestion_jobs (
    id               BIGSERIAL   PRIMARY KEY,
    document_id      BIGINT      NOT NULL REFERENCES rag.documents (id) ON DELETE CASCADE,
    object_key       TEXT        NOT NULL CHECK (char_length(object_key) BETWEEN 1 AND 1024),
    -- '' when the bucket is not versioned, so it can be part of the unique key.
    object_version   TEXT        NOT NULL DEFAULT '' CHECK (char_length(object_version) <= 1024),
    parser_version   TEXT        NOT NULL CHECK (parser_version <> ''),
    chunker_version  TEXT        NOT NULL CHECK (chunker_version <> ''),
    embedding_model  TEXT        NOT NULL CHECK (embedding_model <> ''),
    -- 'skipped': superseded by a newer upload, or the content was already indexed.
    status           TEXT        NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'processing', 'succeeded', 'failed', 'skipped')),
    attempts         INTEGER     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    content_hash     TEXT        CHECK (content_hash ~ '^[0-9a-f]{64}$'),
    chunks           INTEGER     CHECK (chunks >= 0),
    last_error       TEXT        CHECK (char_length(last_error) <= 2000),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Start of the current attempt; a 'processing' job older than the lease is taken over.
    started_at       TIMESTAMPTZ,
    finished_at      TIMESTAMPTZ,
    UNIQUE (document_id, object_key, object_version, parser_version, chunker_version,
            embedding_model)
);

CREATE INDEX ingestion_jobs_status ON rag.ingestion_jobs (status, created_at);
