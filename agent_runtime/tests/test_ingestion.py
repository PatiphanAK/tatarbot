async def test_reprocess_after_embedding_model_change(rig):
    document, version = await rig.upload()
    await rig.deliver(document, version)
    # Same model: a reprocess is a no-op.
    assert await rig.uploads.reprocess(NS, document.id) is True
    message = rig.queue.messages[-1]
    assert message == {"type": "reprocess", "document_id": document.id, "force": False}
    assert await rig.ingestor.reprocess(document.id, False) is Outcome.DONE
    assert rig.embedder.document_calls == 1

    new_model = CountingEmbeddings(identity_suffix=":v2")
    assert await rig.make_ingestor(new_model).reprocess(document.id, False) is Outcome.DONE
    assert new_model.document_calls == 1
    models = rig.scalar("SELECT array_agg(DISTINCT embedding_model) FROM rag.chunks")
    assert models == [new_model.identity]
    # Retrieval with the old model no longer finds it; with the new one it does.
    assert await rig.store().count() == 0
    assert await rig.store(new_model).count() == 1


async def test_force_reprocess_retries_a_failed_document(rig):
    rig.embedder.failures = 10
    rig = Rig(rig.pool, rig.database, rig.embedder, max_attempts=1)
    document, version = await rig.upload()
    assert await rig.deliver(document, version) is Outcome.DONE
    assert (await rig.uploads.get(NS, document.id)).status == DocumentStatus.FAILED
    rig.embedder.failures = 0
    assert await rig.ingestor.reprocess(document.id, False) is Outcome.DONE
    assert (await rig.uploads.get(NS, document.id)).status == DocumentStatus.FAILED
    assert await rig.ingestor.reprocess(document.id, True) is Outcome.DONE
    assert (await rig.uploads.get(NS, document.id)).status == DocumentStatus.READY


async def test_upload_requests_are_validated(rig):
    with pytest.raises(InvalidDocumentError, match="unsupported file type"):
        await rig.uploads.create(NS, "song.mp3", 10)
    with pytest.raises(InvalidDocumentError, match="larger than"):
        await rig.uploads.create(NS, "big.md", rig.settings.max_bytes + 1)
    with pytest.raises(InvalidInputError, match="namespace"):
        await rig.uploads.create("Bad Namespace", "a.md", 10)
    # Path components in the file name are dropped.
    document, _ = await rig.uploads.create(NS, "../../etc/passwd.md", 10)
    assert document.source == "passwd.md"
    assert await rig.uploads.get("discord:7", document.id) is None
    assert [d.id for d in await rig.uploads.list_documents(NS)] == [document.id]


def _key(document, version, model):
    return JobKey(
        document.id,
        document.object_key,
        version,
        PARSER_VERSION,
        KnowledgeSettings().chunker_version,
        model,
    )
