BUCKET = "rag-test"
NS = "discord:42"
GUIDE = b"# Upload guide\n\nUse /upload with an audio file up to 25 MB.\n"


class FakeStorage(ObjectStorage):
    def __init__(self):
        self.objects: dict[str, bytes] = {}
        self.deleted: list[str] = []
        self.presigned: list[tuple[str, int]] = []

    @property
    def bucket(self):
        return BUCKET

    def presign_upload(self, key, max_bytes, expires_seconds):
        self.presigned.append((key, max_bytes))
        return PresignedUpload("https://s3.invalid/", {"key": key}, datetime.now(UTC))

    async def read(self, key, version, max_bytes):
        if key not in self.objects:
            raise ObjectMissingError("gone")
        data = self.objects[key]
        if len(data) > max_bytes:
            raise InvalidDocumentError("too large")
        return StoredObject(data, None)

    async def delete(self, key):
        self.deleted.append(key)
        self.objects.pop(key, None)

    def put(self, key, data):
        """The client's direct upload; returns the S3 event's version token."""
        self.objects[key] = data
        return f"etag:{hash(data)}"


class FakeQueue(IngestQueue):
    def __init__(self):
        self.messages = []

    async def send(self, message):
        self.messages.append(message)


class CountingEmbeddings(HashEmbeddings):
    """Hash embeddings at the schema's size, with scripted failures."""

    def __init__(self, failures=0, identity_suffix=""):
        super().__init__(1024)
        self.failures = failures
        self.document_calls = 0
        self._suffix = identity_suffix

    @property
    def identity(self):
        return super().identity + self._suffix

    async def embed_documents(self, texts):
        self.document_calls += 1
        if self.failures:
            self.failures -= 1
            raise EmbeddingError("embedding backend down")
        return await super().embed_documents(texts)


class Rig:
    def __init__(self, pool, database, embedder=None, **settings):
        self.database = database
        self.storage = FakeStorage()
        self.queue = FakeQueue()
        self.settings = UploadSettings(**settings)
        self.repo = PostgresDocumentRepository(pool, 1024)
        self.embedder = embedder or CountingEmbeddings()
        self.uploads = Uploads(self.repo, self.storage, self.queue, self.settings)
        self.pool = pool
        self.ingestor = self.make_ingestor(self.embedder)

    def make_ingestor(self, embedder):
        return Ingestor(self.repo, self.storage, embedder, KnowledgeSettings(), self.settings)

    async def upload(self, filename="guide.md", data=GUIDE, source=None):
        document, _ = await self.uploads.create(NS, filename, len(data), source)
        version = self.storage.put(document.object_key, data)
        return document, version

    async def deliver(self, document, version, ingestor=None):
        return await (ingestor or self.ingestor).handle_object_created(
            BUCKET, document.object_key, version
        )

    def store(self, embedder=None):
        return PostgresVectorStore(self.pool, (embedder or self.embedder).identity, 1024)

    def scalar(self, query, *params):
        with psycopg.connect(self.database) as conn:
            return conn.execute(query, params).fetchone()[0]


@pytest.fixture
async def pool(database):
    migrate(database)
    pool = create_pool(database, 4)
    await pool.open()
    yield pool
    await pool.close()


@pytest.fixture
def rig(pool, database):
    return Rig(pool, database)


async def test_upload_lifecycle(rig):
    document, version = await rig.upload()
    assert document.status == DocumentStatus.PENDING_UPLOAD
    assert document.namespace == NS and document.source == "guide.md"
    # Key generated by the runtime, extension kept; size limit passed to the presigned POST.
    key, max_bytes = rig.storage.presigned[0]
    assert key.startswith("rag/") and key.endswith(".md") and key == document.object_key
    assert max_bytes == rig.settings.max_bytes

    assert await rig.deliver(document, version) is Outcome.DONE
    ready = await rig.uploads.get(NS, document.id)
    assert ready.status == DocumentStatus.READY
    assert ready.title == "Upload guide"
    assert ready.mime_type == "text/markdown" and ready.size_bytes == len(GUIDE)
    assert ready.chunks == 1 and ready.error is None

    hits = await rig.store().search(
        await rig.embedder.embed_query("upload audio file"), 3, namespaces=["global", NS]
    )
    assert hits and hits[0].chunk.title == "Upload guide"
    # Not visible from another server.
    assert await rig.store().search([1.0] * 1024, 3, namespaces=["global", "discord:7"]) == []


async def test_duplicate_events_are_idempotent(rig):
    document, version = await rig.upload()
    for _ in range(3):
        assert await rig.deliver(document, version) is Outcome.DONE
    assert rig.embedder.document_calls == 1
    assert rig.scalar("SELECT count(*) FROM rag.chunks") == 1
    assert rig.scalar("SELECT count(*) FROM rag.ingestion_jobs") == 1


async def test_reupload_replaces_only_when_ready(rig):
    first, v1 = await rig.upload()
    await rig.deliver(first, v1)
    second, v2 = await rig.upload(data=b"# Upload guide\n\nNew limit: 50 MB.\n")
    assert second.id == first.id and second.object_key != first.object_key
    # The previous object is deleted; the previous chunks stay live until the new ones are in.
    assert rig.storage.deleted == [first.object_key]
    pending = await rig.uploads.get(NS, first.id)
    assert pending.status == DocumentStatus.PENDING_UPLOAD and pending.chunks == 1
    # A late event for the old object is ignored.
    assert await rig.deliver(first, v1) is Outcome.DONE

    await rig.deliver(second, v2)
    text = rig.scalar("SELECT content FROM rag.chunks")
    assert "50 MB" in text
    assert rig.scalar("SELECT count(*) FROM rag.chunks") == 1


async def test_unchanged_content_is_not_re_embedded(rig):
    first, v1 = await rig.upload()
    await rig.deliver(first, v1)
    second, v2 = await rig.upload()  # same bytes, new object
    await rig.deliver(second, v2)
    assert rig.embedder.document_calls == 1
    document = await rig.uploads.get(NS, first.id)
    assert document.status == DocumentStatus.READY and document.chunks == 1


async def test_invalid_content_fails_without_retry(rig):
    document, version = await rig.upload(filename="notes.txt", data=b"%PDF-1.7 binary")
    assert await rig.deliver(document, version) is Outcome.DONE
    failed = await rig.uploads.get(NS, document.id)
    assert failed.status == DocumentStatus.FAILED
    assert "PDF" in failed.error
    assert failed.chunks == 0
    assert rig.embedder.document_calls == 0


async def test_transient_failure_is_retried(rig):
    rig.embedder.failures = 1
    document, version = await rig.upload()
    assert await rig.deliver(document, version) is Outcome.RETRY
    queued = await rig.uploads.get(NS, document.id)
    assert queued.status == DocumentStatus.QUEUED
    assert "embedding backend down" in queued.error
    assert queued.chunks == 0
    # SQS redelivers the same event.
    assert await rig.deliver(document, version) is Outcome.DONE
    assert (await rig.uploads.get(NS, document.id)).status == DocumentStatus.READY
    assert rig.scalar("SELECT attempts FROM rag.ingestion_jobs") == 2


async def test_gives_up_after_max_attempts(pool, database):
    rig = Rig(pool, database, CountingEmbeddings(failures=10), max_attempts=2)
    document, version = await rig.upload()
    assert await rig.deliver(document, version) is Outcome.RETRY
    # The last attempt fails for good and the message is acknowledged.
    assert await rig.deliver(document, version) is Outcome.DONE
    failed = await rig.uploads.get(NS, document.id)
    assert failed.status == DocumentStatus.FAILED
    assert await rig.deliver(document, version) is Outcome.DONE
    assert rig.embedder.document_calls == 2


async def test_failed_reupload_keeps_previous_version_live(rig):
    first, v1 = await rig.upload()
    await rig.deliver(first, v1)
    second, v2 = await rig.upload(data=b"\x00\x01 binary")
    await rig.deliver(second, v2)
    document = await rig.uploads.get(NS, first.id)
    assert document.status == DocumentStatus.FAILED
    assert document.chunks == 1  # the previous complete version
    assert "25 MB" in rig.scalar("SELECT content FROM rag.chunks")


async def test_busy_job_is_retried_and_crashed_worker_is_taken_over(rig):
    document, version = await rig.upload()
    # Another worker claimed the job and is still within its lease.
    job = await rig.repo.ensure_job(_key(document, version, rig.embedder.identity))
    await rig.repo.claim_job(job.id, 300, 5)
    assert await rig.deliver(document, version) is Outcome.RETRY
    # It crashed: once the lease has expired, the job is taken over.
    with psycopg.connect(rig.database) as conn:
        conn.execute(
            "UPDATE rag.ingestion_jobs SET started_at = now() - interval '1 hour' WHERE id = %s",
            (job.id,),
        )
    assert await rig.deliver(document, version) is Outcome.DONE
    assert (await rig.uploads.get(NS, document.id)).status == DocumentStatus.READY


async def test_delete_cascades_and_late_events_are_ignored(rig):
    document, version = await rig.upload()
