//! Composition of the server library (Phase 1.5): the only place that knows
//! its concrete adapters. Builds without touching the network; background
//! tasks connect to Postgres, create the local bucket and sweep orphans.

use std::sync::Arc;
use std::time::Duration;

use crate::adapters::outbound::attachment_fetch::HttpAttachmentFetcher;
use crate::adapters::outbound::audio_http;
use crate::adapters::outbound::ffmpeg::{Ffmpeg, FfmpegSettings};
use crate::adapters::outbound::pg_library::{self, PgLibrary};
use crate::adapters::outbound::s3_store::{S3Settings, S3Store};
use crate::application::ports::{LibraryService, ObjectStore};
use crate::application::use_cases::{LibrarySettings, LibraryUseCase};
use crate::config::LibraryConfig;
use crate::error::AppError;

/// Orphans younger than this are never swept (an upload may be mid-flight).
const SWEEP_GRACE: Duration = Duration::from_secs(60 * 60);
const SWEEP_INTERVAL: Duration = Duration::from_secs(60 * 60);

pub struct Library {
    pub service: Arc<dyn LibraryService>,
    pub store: Arc<dyn ObjectStore>,
    pub upload_role: String,
}

pub async fn build(cfg: LibraryConfig) -> Result<Library, AppError> {
    let repo = PgLibrary::connect_lazy(&cfg.database_url, cfg.max_connections).map_err(|e| {
        AppError::InvalidEnv {
            key: "DATABASE_URL",
            reason: e.to_string(),
        }
    })?;
    tokio::spawn(repo.clone().supervise());

    let store = S3Store::new(S3Settings {
        bucket: cfg.bucket,
        endpoint: cfg.endpoint,
    })
    .await;
    if cfg.create_bucket {
        let store = store.clone();
        tokio::spawn(async move {
            for attempt in 1..=10 {
                match store.ensure_bucket().await {
                    Ok(()) => return,
                    Err(err) => tracing::warn!(%err, attempt, "cannot create library bucket yet"),
                }
                tokio::time::sleep(Duration::from_secs(3)).await;
            }
        });
    }
    let shared_store: Arc<dyn ObjectStore> = Arc::new(store.clone());
    tokio::spawn(pg_library::sweep_periodically(
        repo.clone(),
        shared_store.clone(),
        cfg.prefix.clone(),
        SWEEP_GRACE,
        SWEEP_INTERVAL,
    ));

    let ffmpeg = Ffmpeg::new(FfmpegSettings {
        ffmpeg: cfg.ffmpeg,
        ffprobe: cfg.ffprobe,
        ..FfmpegSettings::default()
    });
    let fetcher = HttpAttachmentFetcher::new(audio_http::client()?);
    let service = LibraryUseCase::new(
        repo,
        store,
        ffmpeg,
        fetcher,
        LibrarySettings::new(cfg.prefix, cfg.quota_bytes),
    );
    Ok(Library {
        service: Arc::new(service),
        store: shared_store,
        upload_role: cfg.upload_role,
    })
}

/// End to end with real Postgres, RustFS and ffmpeg (only the Discord
/// download is faked): upload, dedupe, play the stored object through
/// Songbird's input pipeline from a presigned URL, delete. `make test-db`.
#[cfg(test)]
mod tests {
    use std::path::Path;

    use async_trait::async_trait;
    use songbird::input::codecs::{get_codec_registry, get_probe};
    use songbird::input::{Input, LiveInput};
    use sqlx::PgPool;
    use symphonia::core::codecs::CODEC_TYPE_OPUS;

    use super::*;
    use crate::adapters::outbound::songbird_voice::{LibraryAudio, SongbirdVoice};
    use crate::application::ports::{
        Attachment, AttachmentFetcher, FetchError, Fetched, LibraryError, UploadRequest,
    };
    use crate::domain::library::ContentHash;
    use crate::domain::music::{GuildId, TrackSource, UserId};

    /// Serves a sine wave generated by ffmpeg as the "attachment".
    struct GeneratedMp3;

    #[async_trait]
    impl AttachmentFetcher for GeneratedMp3 {
        async fn fetch(&self, _: &str, _: u64, dest: &Path) -> Result<Fetched, FetchError> {
            let ok = tokio::process::Command::new("ffmpeg")
                .args([
                    "-v",
                    "error",
                    "-y",
                    "-f",
                    "lavfi",
                    "-i",
                    "sine=frequency=440:duration=3",
                ])
                .args(["-f", "mp3"])
                .arg(dest)
                .status()
                .await
                .unwrap()
                .success();
            assert!(ok);
            let bytes = tokio::fs::read(dest).await.unwrap();
            use sha2::Digest;
            Ok(Fetched {
                size_bytes: bytes.len() as u64,
                hash: ContentHash::from_digest(&sha2::Sha256::digest(&bytes)),
            })
        }
    }

    fn request(guild: u64) -> UploadRequest {
        UploadRequest {
            guild: GuildId(guild),
            user: UserId(7),
            can_upload: true,
            attachment: Attachment {
                url: "https://cdn.discordapp.com/attachments/1/2/tone.mp3".into(),
                filename: "tone.mp3".into(),
                declared_size: 1000,
            },
            title: Some("Test Tone".into()),
        }
    }

    #[sqlx::test(migrations = "./migrations")]
    #[ignore = "needs DATABASE_URL, RustFS and ffmpeg (make test-db)"]
    async fn library_end_to_end(pool: PgPool) {
        let prefix = format!("e2e-{}/", std::process::id());
        let store = S3Store::new(S3Settings {
            bucket: std::env::var("MUSIC_S3_BUCKET").unwrap_or_else(|_| "tatarbot-test".into()),
            endpoint: Some(std::env::var("MUSIC_S3_ENDPOINT").expect("MUSIC_S3_ENDPOINT")),
        })
        .await;
        store.ensure_bucket().await.unwrap();
        let library = LibraryUseCase::new(
            PgLibrary::from_pool(pool, true),
            store.clone(),
            Ffmpeg::new(FfmpegSettings::default()),
            GeneratedMp3,
            LibrarySettings::new(prefix.clone(), 10 * 1024 * 1024),
        );

        let first = library.upload(request(1)).await.unwrap();
        assert!(!first.reused_audio);
        assert_eq!(first.track.title, "Test Tone");
        assert!((first.track.duration.as_secs_f64() - 3.0).abs() < 0.2);
        // The same bytes (lavfi output is deterministic) in another server.
        let second = library.upload(request(2)).await.unwrap();
        assert!(second.reused_audio);
        assert!(matches!(
            library.upload(request(1)).await,
            Err(LibraryError::AlreadyInLibrary(_))
        ));

        // Play it the way the voice adapter does: presign at start, stream.
        let key = library.object_key(&first.track.hash);
        let store_dyn: Arc<dyn ObjectStore> = Arc::new(store.clone());
        let voice = SongbirdVoice::new(
            songbird::Songbird::serenity(),
            audio_http::client().unwrap(),
            Some(Arc::new(LibraryAudio {
                store: store_dyn.clone(),
                http: audio_http::trusted_client().unwrap(),
            })),
        );
        let input = voice
            .input_for_test(&TrackSource::Library { key: key.clone() })
            .make_playable_async(get_codec_registry(), get_probe())
            .await
            .unwrap();
        let Input::Live(LiveInput::Parsed(mut parsed), _) = input else {
            panic!("not parsed");
        };
        let track = parsed.format.default_track().unwrap().codec_params.clone();
        assert_eq!(
            track.codec, CODEC_TYPE_OPUS,
            "stored audio must be Opus for passthrough"
        );
        assert_eq!(track.sample_rate, Some(48_000));
        for _ in 0..10 {
            let packet = parsed.format.next_packet().unwrap();
            parsed.decoder.decode(&packet).unwrap();
        }

        // Deleting both rows removes the object.
        library
            .delete(GuildId(1), UserId(7), false, first.track.id)
            .await
            .unwrap();
        assert!(store_dyn.last_modified(&key).await.unwrap().is_some());
        library
            .delete(GuildId(2), UserId(7), false, second.track.id)
            .await
            .unwrap();
        assert_eq!(store_dyn.last_modified(&key).await.unwrap(), None);
    }
}
